/**
 * generate-redirects.mjs — turn config/redirects.json into host-specific redirect files.
 *
 * docs/redirect-map.md promises "the map is the source; the file below is generated from it —
 * do not hand-maintain both." This is that generator. Three deploy targets are still in play
 * (Hostinger static, Hostinger Apache, Vercel/Netlify), and maintaining three redirect files
 * by hand is how one of them silently ends up a version behind.
 *
 * Usage:
 *   node scripts/generate-redirects.mjs                 # write all formats to build/redirects/
 *   node scripts/generate-redirects.mjs --emit netlify  # one format only
 *   node scripts/generate-redirects.mjs --strict        # FAIL if the map is not launch-ready
 *
 * `--strict` is the launch gate: it refuses to generate from a map that still has a null
 * canonical domain (D-03) or an empty page list (D-01). Without it the script still runs, so
 * the tooling can be exercised and reviewed before those decisions land.
 *
 * Output goes to build/redirects/ (gitignored) rather than straight into public/. Dropping a
 * redirect file into public/ makes it part of every build, including previews — and a preview
 * carrying production redirects is its own small disaster.
 */
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const configPath = join(root, 'config', 'redirects.json');
const outDir = join(root, 'build', 'redirects');

const args = process.argv.slice(2);
const strict = args.includes('--strict');
const emitArg = args.indexOf('--emit');
const only = emitArg !== -1 ? args[emitArg + 1] : null;

const config = JSON.parse(readFileSync(configPath, 'utf8'));
const { canonicalDomain, legacyDomains = [], pages = [] } = config;

/* ----------------------------------------------------------------- validation */

const problems = [];
if (!canonicalDomain) {
  problems.push(
    'canonicalDomain is null — BLOCKED on D-03. Every rule is written against it; ' +
      'generating now would produce redirects pointing nowhere.',
  );
}
if (pages.length === 0) {
  problems.push(
    'pages[] is empty — BLOCKED on D-01. The old-URL inventory (crawl + Search Console + ' +
      'GA4 + old sitemap, see docs/redirect-map.md Step 1) has not been collected. ' +
      'Cutting over with an empty map discards every ranking the old site holds.',
  );
}

// Real correctness checks — these apply whenever pages ARE filled.
const seen = new Set();
for (const [i, p] of pages.entries()) {
  const where = `pages[${i}]`;
  if (!p.from?.startsWith('/')) problems.push(`${where}: 'from' must be a site-relative path starting with "/" (got ${JSON.stringify(p.from)})`);
  if (!p.to) problems.push(`${where}: missing 'to'`);
  if (p.from === p.to) problems.push(`${where}: '${p.from}' redirects to itself — an infinite loop`);
  if (seen.has(p.from)) problems.push(`${where}: duplicate rule for '${p.from}' — the first one wins and the second is dead`);
  seen.add(p.from);
  if (p.status && p.status !== 301) {
    problems.push(
      `${where}: status ${p.status} — a migration must use 301. A 302 tells Google to keep ` +
        'the OLD url indexed, which is the opposite of the goal.',
    );
  }
}
// A → B → C chains leak equity and are trivially avoidable by pointing A straight at C.
for (const p of pages) {
  const next = pages.find((q) => q.from === p.to);
  if (next) {
    problems.push(
      `pages: '${p.from}' → '${p.to}' → '${next.to}' is a redirect CHAIN. ` +
        `Point '${p.from}' directly at '${next.to}'.`,
    );
  }
}

if (problems.length) {
  console.error('\nRedirect map is not launch-ready:\n');
  for (const p of problems) console.error(`  ✗ ${p}`);
  console.error('');
  if (strict) process.exit(1);
  console.error('Continuing anyway (no --strict). Output below is a TEMPLATE, not shippable.\n');
}

/* ------------------------------------------------------------------ generators */

const DOMAIN = canonicalDomain ?? 'CANONICAL-DOMAIN-TODO-D-03';
const abs = (path) => `https://${DOMAIN}${path}`;

function netlify() {
  const lines = [
    '# GENERATED by scripts/generate-redirects.mjs from config/redirects.json.',
    '# Do not edit by hand — edit the config and regenerate.',
    '',
    '# --- page-level (old site → new site) ---',
  ];
  for (const p of pages) {
    lines.push(`${p.from}  ${p.to}  ${p.status ?? 301}${p.note ? `  # ${p.note}` : ''}`);
  }
  if (!pages.length) lines.push('# (empty — see BLOCKED D-01 in config/redirects.json)');
  lines.push('', '# --- legacy domains (wildcard, applied last) ---');
  for (const d of legacyDomains) {
    lines.push(`http://${d.domain}/*   ${abs(d.to)}  301!`);
    lines.push(`https://${d.domain}/*  ${abs(d.to)}  301!`);
    lines.push(`http://www.${d.domain}/*   ${abs(d.to)}  301!`);
    lines.push(`https://www.${d.domain}/*  ${abs(d.to)}  301!`);
  }
  return lines.join('\n') + '\n';
}

function vercel() {
  const redirects = [
    ...pages.map((p) => ({ source: p.from, destination: p.to, permanent: true })),
    ...legacyDomains.map((d) => ({
      source: '/(.*)',
      has: [{ type: 'host', value: `(www\\.)?${d.domain.replace(/\./g, '\\.')}` }],
      destination: abs(d.to),
      permanent: true,
    })),
  ];
  return JSON.stringify({ redirects }, null, 2) + '\n';
}

function apache() {
  const lines = [
    '# GENERATED by scripts/generate-redirects.mjs from config/redirects.json.',
    '# Do not edit by hand — edit the config and regenerate.',
    '',
    'RewriteEngine On',
    '',
    '# Force https and a single host spelling FIRST, so an old URL resolves in ONE hop',
    '# rather than http→https→new (a two-hop chain leaks equity for no reason).',
    'RewriteCond %{HTTPS} off [OR]',
    `RewriteCond %{HTTP_HOST} !^${DOMAIN.replace(/\./g, '\\.')}$ [NC]`,
    `RewriteRule ^(.*)$ https://${DOMAIN}/$1 [R=301,L]`,
    '',
    '# --- page-level ---',
  ];
  for (const p of pages) {
    if (p.note) lines.push(`# ${p.note}`);
    lines.push(`Redirect ${p.status ?? 301} ${p.from} ${p.to}`);
  }
  if (!pages.length) lines.push('# (empty — see BLOCKED D-01 in config/redirects.json)');
  lines.push('', '# --- legacy domains: configure on THOSE domains\' vhosts, not this one ---');
  for (const d of legacyDomains) {
    lines.push(`#   ${d.domain}  →  ${abs(d.to)}   (301, wildcard)`);
  }
  return lines.join('\n') + '\n';
}

/* ---------------------------------------------------------------------- write */

const formats = {
  netlify: { file: '_redirects', gen: netlify },
  vercel: { file: 'vercel.redirects.json', gen: vercel },
  apache: { file: '.htaccess', gen: apache },
};

if (only && !formats[only]) {
  console.error(`Unknown --emit target '${only}'. Expected one of: ${Object.keys(formats).join(', ')}`);
  process.exit(1);
}

mkdirSync(outDir, { recursive: true });
const targets = only ? [only] : Object.keys(formats);
for (const name of targets) {
  const { file, gen } = formats[name];
  writeFileSync(join(outDir, file), gen(), 'utf8');
  console.log(`  wrote build/redirects/${file}  (${name})`);
}

console.log(
  `\n${pages.length} page rule(s), ${legacyDomains.length} legacy domain(s), canonical: ${canonicalDomain ?? '(unset — D-03)'}\n`,
);
console.log('Copy the file for your host into place at deploy time. Do not commit it to public/ —');
console.log('that would ship production redirects in every preview build.\n');
